"""
table_comparison.py -- the model-data comparison as a LaTeX table (manuscript Table 2).

For every effect: the observed group mean and its 95% confidence interval, and for each
model the minimum and maximum over the admissible parameter vectors, the number and
percentage of vectors that reproduce the observed magnitude, do not reproduce it, or are
numerically uncertain, and, for effects whose direction the derivations do not fix, the
number of vectors whose effect is significantly of the observed sign, of the opposite
sign, or of uncertain sign (classify.py; effects.SIGN_FIXED).

Reads results/classification.json. Writes ../manuscript/latex/table_comparison.tex.
"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from effects import GROUPS, NAMES, SRC, SIGN_FIXED

C = json.load(open('results/classification.json'))
OUT = '../manuscript/latex/table_comparison.tex'


def num(x, k):
    """Three significant figures, or whole milliseconds for response-time effects."""
    if SRC[k][1] == 1000.0:
        t = f'{x:.0f}'
    elif abs(x) >= 1e-3 or x == 0:
        t = f'{x:.3g}'
    else:
        m, e = f'{x:.1e}'.split('e')
        t = f'{m}$\\times 10^{{{int(e)}}}$'
    return t.replace('-', '$-$', 1) if t.startswith('-') else t


def tex(s):
    return (s.replace('\n', ' ').replace('%', r'\%').replace('/s$^2$', 's$^{-2}$')
             .replace('/s$^3$', 's$^{-3}$').replace('(/s)', '(s$^{-1}$)'))


lines = [r'\begin{tabular}{l l l r r r r r l}',
         r'\toprule',
         r'Effect & Observed [95\% CI] & Model & Min & Max & Reproduced & Not reproduced'
         r' & Uncertain & Sign: observed / opposite / uncertain \\',
         r'\midrule']
for g, (group, keys) in enumerate(GROUPS):
    if g:
        lines.append(r'\midrule')
    lines.append(r'\multicolumn{9}{l}{\emph{' + group + r'}} \\')
    for k in keys:
        o = C['observed'][k]
        obs = f"{num(o['mean'], k)} [{num(o['lo'], k)}, {num(o['hi'], k)}]"
        for i, tag in enumerate(('model1', 'model2')):
            m = C['models'][tag][k]; n = m['n']
            pct = lambda v: f'{v} ({100 * v / n:.0f}\\%)'
            sign = ('--' if k in SIGN_FIXED else
                    f"{m['sign_observed']} / {m['sign_opposite']} / {m['sign_uncertain']}")
            lines.append(' & '.join([
                tex(NAMES[k]) if i == 0 else '', obs if i == 0 else '',
                str(i + 1), num(m['min'], k), num(m['max'], k),
                pct(m['reproduces']), pct(m['does_not']), pct(m['uncertain']),
                sign]) + r' \\')
lines += [r'\bottomrule', r'\end{tabular}']
n1 = C['models']['model1']['n_admissible']; n2 = C['models']['model2']['n_admissible']
open(OUT, 'w').write('% generated by scripts/table_comparison.py -- do not edit\n'
                     f'% admissible parameter vectors: Model 1 {n1}, Model 2 {n2}\n'
                     + '\n'.join(lines) + '\n')
print('wrote', OUT)
