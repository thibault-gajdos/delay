"""
stats_tables_tex.py -- the ANOVA tables of the manuscript, from R/stats_results.csv.

Writes, in ../manuscript/latex/:
  table_behav.tex   accuracy, mean RT, mean PMET, mean MET
  table_pma.tex     partial-activation rate, stimulus and delay periods
  table_lrp.tex     lateralized readiness potential, all four periods
  table_mbl.tex     mu-beta lateralization, stimulus and delay periods
Each file holds one tabular; captions and labels are in the manuscript. For the rows
testing a time contrast against zero, the estimate and its 95% confidence interval are
given: the slope of the least-squares fit on time in seconds, and the coefficient of the
squared time term (R/run_stats.R).
"""
import csv

OUT = '../manuscript/latex/'
ROWS = list(csv.DictReader(open('R/stats_results.csv')))
NAME = {'dur': 'duration', 'coh': 'coherence', 'dur:coh': 'duration $\\times$ coherence'}
PERIODS = {'stimulus': 'Stimulus', 'delay': 'Delay', 'RS': 'Response signal',
           'response': 'Response'}


def p_txt(p):
    p = float(p)
    return '$p<.001$' if p < .001 else '$p=' + f'{p:.3f}'.lstrip('0') + '$'


def df_txt(x):
    x = float(x)
    return f'{x:.0f}' if abs(x - round(x)) < 1e-9 else f'{x:.2f}'


def g(x):
    t = f'{float(x):.3g}'
    return t.replace('-', '$-$', 1)


def effect_txt(e):
    e = NAME.get(e, e)
    return e.replace(' x ', ' $\\times$ ')


def tabular(blocks, est):
    """blocks: list of (label, rows). est: whether to add the estimate column."""
    cols = 'l l r r r l r' + (' l' if est else '')
    head = ['Period' if est else 'Measure', 'Effect', 'df1', 'df2', '$F$', '$p$',
            '$\\eta_p^2$'] + (['Estimate [95\\% CI]'] if est else [])
    out = ['\\begin{tabular}{' + cols + '}', '\\toprule', ' & '.join(head) + ' \\\\',
           '\\midrule']
    for i, (label, rows) in enumerate(blocks):
        if i:
            out.append('\\midrule')
        for j, r in enumerate(rows):
            cells = [label if j == 0 else '', effect_txt(r['effect']), df_txt(r['df1']),
                     df_txt(r['df2']), f"{float(r['F']):.3f}", p_txt(r['p']),
                     f"{float(r['eta2p']):.3f}"]
            if est:
                cells.append(f"{g(r['estimate'])} [{g(r['ci_lo'])}, {g(r['ci_hi'])}]"
                             if r['estimate'] not in ('', 'NA') else '')
            out.append(' & '.join(cells) + ' \\\\')
    out += ['\\bottomrule', '\\end{tabular}']
    return '% generated by scripts/stats_tables_tex.py -- do not edit\n' + '\n'.join(out) + '\n'


def sel(measure, period):
    return [r for r in ROWS if r['measure'] == measure and r['period'] == period]


open(OUT + 'table_behav.tex', 'w').write(tabular(
    [(m, sel(m, 'behaviour')) for m in ('Accuracy', 'Mean RT', 'Mean PMET', 'Mean MET')],
    est=False))
for measure, periods, fname in (('PMA', ('stimulus', 'delay'), 'table_pma.tex'),
                                ('LRP', ('stimulus', 'delay', 'RS', 'response'),
                                 'table_lrp.tex'),
                                ('MBL', ('stimulus', 'delay'), 'table_mbl.tex')):
    open(OUT + fname, 'w').write(tabular(
        [(PERIODS[p], sel(measure, p)) for p in periods], est=True))
print('wrote table_behav.tex, table_pma.tex, table_lrp.tex, table_mbl.tex')
